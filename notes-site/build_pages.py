"""Render the existing editor template for the GitHub Pages client."""

import os
import re
import sys
from pathlib import Path
from types import SimpleNamespace


ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "vendor"))
os.environ["DJANGO_SETTINGS_MODULE"] = "config.settings"
os.environ["DJANGO_DATABASE_URL"] = ""
os.environ["DJANGO_DATABASE_PASSWORD"] = ""
os.environ["DJANGO_DEBUG"] = "1"

import django

django.setup()

from django.template.loader import render_to_string
from django.test.utils import override_settings
from notes.models import Page, default_drawing_palettes, default_drawing_tools


def render_page(view, data, script):
    with override_settings(STATIC_URL="/notes-site/static/"):
        document = render_to_string(f"notes/{view}.html", data)
    document = document.replace('"/notes-site/static/', '"../notes-site/static/')
    document = document.replace('<main class="site-main">', '<p id="cloudStatus" role="status">공책을 불러오는 중…</p><main class="site-main" hidden>')
    document = document.replace("</body>", '<script src="https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2.93.3/dist/umd/supabase.js" '
                                'integrity="sha384-+ZU0FLgmXrUNVwx4Nmuay6i8PA8Ouf1KPCdacpklfY0SOT3teDcnp9j74VIF2evS" crossorigin="anonymous"></script>\n'
                                f'<script type="module" src="./{script}"></script>\n</body>')
    document = re.sub(r'<script src="\.\./notes-site/static/notes/(editor|study|organize)\.js\?[^"]+"></script>', '', document)
    return document.replace("</head>", '<link rel="stylesheet" href="./cloud.css">\n</head>')


def build():
    user = SimpleNamespace(id=1)
    notebook = SimpleNamespace(id=1, owner_id=1, title="공책", subject="")
    page = Page(id=1)
    chapter = SimpleNamespace(id=1, title="챕터", pages=SimpleNamespace(all=[page]))
    editor = render_page("editor", {
        "user": user,
        "notebook": notebook,
        "chapters": [chapter],
        "current_page": page,
        "has_custom_paper": True,
        "local_ocr_enabled": False,
        "csrf_token": "static-page",
        "page_previews": [],
        "drawing_preferences": {
            "tools": default_drawing_tools(),
            "palettes": default_drawing_palettes(),
            "active_palette": "basic",
            "eraser_mode": "stroke",
            "palm_rejection": "auto",
        },
    }, "editor.js")
    study = render_page("study", {"notebook": notebook, "study_payload": [], "csrf_token": "static-page"}, "study.js")
    organize_data = {"notebook": notebook, "source": [], "items": [], "csrf_token": "static-page"}
    output = ROOT.parent / "cloud"
    output.mkdir(exist_ok=True)
    documents = {
        "editor": editor,
        "study": study,
        "organize": render_page("organize", {**organize_data, "kind": "reorder"}, "organize.js"),
        "map": render_page("organize", {**organize_data, "kind": "map"}, "organize.js"),
    }
    for name, document in documents.items():
        clean = "\n".join(line.rstrip() for line in document.splitlines())
        (output / f"{name}.html").write_text(f"<!-- Generated by notes-site/build_pages.py. -->\n{clean}\n", encoding="utf-8")


if __name__ == "__main__":
    build()
